package com.vasmarfas.networkhelm.routeros.schema

fun label(property: String): String =
    property.split(separators).flatMap { it.split(humps) }.filter { it.isNotEmpty() }.mapIndexed { index, word ->
        when {
            word == "src" || word == "dst" || index == 0 && (word == "in" || word == "out") -> capitalised(word) + "."
            else -> spellings[word] ?: capitalised(word)
        }
    }.joinToString(" ")

private val separators = Regex("""[-_]|(?<!\d)\.|\.(?!\d)""")

private val humps = Regex("""(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z]{2})(?=[A-Z][a-z])""")

private fun capitalised(word: String) = word.replaceFirstChar(Char::uppercaseChar)

